interface GeometricSolids3DViewerProps {
  initialSolid?: SolidType;
  rotationX?: number;
  rotationY?: number;
  zoom?: number;
  onUpdateTransform?: (props: { rotationX?: number; rotationY?: number; zoom?: number }) => void;
  isImmersive?: boolean;
}

export const GeometricSolids3DViewer: React.FC<GeometricSolids3DViewerProps> = ({
  initialSolid = 'cube',
  rotationX = 0.4,
  rotationY = -0.5,
  zoom = 1,
  onUpdateTransform,
  isImmersive = false,
}) => {
  const mountRef = useRef<HTMLDivElement>(null);
  const [selectedSolid, setSelectedSolid] = useState<SolidType>(initialSolid);
  const [internalZoom, setInternalZoom] = useState(zoom);
  const [showWireframe, setShowWireframe] = useState(true);
  const [showVertices, setShowVertices] = useState(true);
  const [isRotating, setIsRotating] = useState(true);
  const [selectedElement, setSelectedElement] = useState<'faces' | 'edges' | 'vertices' | 'euler'>('euler');

  const sceneRef = useRef<THREE.Scene | null>(null);
  const cameraRef = useRef<THREE.PerspectiveCamera | null>(null);
  const rendererRef = useRef<THREE.WebGLRenderer | null>(null);
  const solidGroupRef = useRef<THREE.Group | null>(null);
  const animFrameRef = useRef<number | null>(null);

  // Interaction refs
  const isDraggingRef = useRef(false);
  const prevMousePosRef = useRef({ x: 0, y: 0 });
  const rotXRef = useRef(rotationX);
  const rotYRef = useRef(rotationY);

  const currentMeta = SOLIDS_METADATA[selectedSolid];

  // Helper to build 3D mesh based on active solid type
  const buildSolidMesh = useCallback((group: THREE.Group, solid: SolidType) => {
    // Clear old children and dispose geometries
    while (group.children.length > 0) {
      const child = group.children[0] as any;
      if (child.geometry) child.geometry.dispose();
      if (child.material) {
        if (Array.isArray(child.material)) {
          child.material.forEach((m: any) => m.dispose());
        } else {
          child.material.dispose();
        }
      }
      group.remove(child);
    }

    let geometry: THREE.BufferGeometry;
    const baseRadius = 2.0;

    switch (solid) {
      case 'tetrahedron':
        geometry = new THREE.TetrahedronGeometry(baseRadius, 0);
        break;
      case 'cube':
        geometry = new THREE.BoxGeometry(2.4, 2.4, 2.4);
        break;
      case 'octahedron':
        geometry = new THREE.OctahedronGeometry(baseRadius, 0);
        break;
      case 'dodecahedron':
        geometry = new THREE.DodecahedronGeometry(baseRadius, 0);
        break;
      case 'icosahedron':
        geometry = new THREE.IcosahedronGeometry(baseRadius, 0);
        break;
      case 'cylinder':
        geometry = new THREE.CylinderGeometry(1.4, 1.4, 2.8, 32);
        break;
      case 'sphere':
        geometry = new THREE.SphereGeometry(1.8, 36, 36);
        break;
      default:
        geometry = new THREE.BoxGeometry(2.4, 2.4, 2.4);
    }

    // 1. Semi-transparent Colored Faces
    const faceMaterial = new THREE.MeshStandardMaterial({
      color:
        solid === 'cube'
          ? 0x38bdf8
          : solid === 'tetrahedron'
          ? 0xf43f5e
          : solid === 'octahedron'
          ? 0x10b981
          : solid === 'dodecahedron'
          ? 0xa855f7
          : solid === 'icosahedron'
          ? 0xf59e0b
          : solid === 'cylinder'
          ? 0x06b6d4
          : 0xec4899,
      roughness: 0.3,
      metalness: 0.15,
      transparent: true,
      opacity: 0.72,
      side: THREE.DoubleSide,
    });
    const faceMesh = new THREE.Mesh(geometry, faceMaterial);
    group.add(faceMesh);

    // 2. Wireframe / Edge Outlines
    if (showWireframe) {
      const wireframeGeometry = new THREE.WireframeGeometry(geometry);
      const wireframeMaterial = new THREE.LineBasicMaterial({
        color: 0xffffff,
        linewidth: 2,
        transparent: true,
        opacity: 0.9,
      });
      const wireframe = new THREE.LineSegments(wireframeGeometry, wireframeMaterial);
      group.add(wireframe);
    }

    // 3. Highlighted Vertex Spheres for Polyhedra
    if (showVertices && solid !== 'sphere' && solid !== 'cylinder') {
      const pos = geometry.attributes.position;
      const vertexGroup = new THREE.Group();
      const vertexSphereGeo = new THREE.SphereGeometry(0.12, 16, 16);
      const vertexMat = new THREE.MeshStandardMaterial({
        color: 0xfacc15, // Golden vertex pin
        roughness: 0.2,
        metalness: 0.4,
        emissive: 0xca8a04,
        emissiveIntensity: 0.5,
      });

      // Collect unique vertices
      const uniquePoints: THREE.Vector3[] = [];
      const threshold = 0.001;
      for (let i = 0; i < pos.count; i++) {
        const pt = new THREE.Vector3(pos.getX(i), pos.getY(i), pos.getZ(i));
        const exists = uniquePoints.some((u) => u.distanceTo(pt) < threshold);
        if (!exists) {
          uniquePoints.push(pt);
          const vMesh = new THREE.Mesh(vertexSphereGeo, vertexMat);
          vMesh.position.copy(pt);
          vertexGroup.add(vMesh);
        }
      }
      group.add(vertexGroup);
    }
  }, [showWireframe, showVertices]);

  // Initial Scene Setup
  useEffect(() => {
    const container = mountRef.current;
    if (!container) return;

    const scene = new THREE.Scene();
    sceneRef.current = scene;

    const width = container.clientWidth || 340;
    const height = container.clientHeight || 340;

    const camera = new THREE.PerspectiveCamera(45, width / height, 0.1, 1000);
    camera.position.set(0, 0, 7.5 / internalZoom);
    cameraRef.current = camera;

    const renderer = new THREE.WebGLRenderer({ antialias: true, alpha: true, preserveDrawingBuffer: true });
    renderer.setSize(width, height);
    renderer.setPixelRatio(Math.min(window.devicePixelRatio, 2));
    renderer.outputColorSpace = THREE.SRGBColorSpace;
    container.innerHTML = '';
    container.appendChild(renderer.domElement);
    rendererRef.current = renderer;

    // Lighting
    const ambientLight = new THREE.AmbientLight(0xffffff, 1.4);
    scene.add(ambientLight);

    const dirLight1 = new THREE.DirectionalLight(0xffffff, 2.2);
    dirLight1.position.set(5, 8, 6);
    scene.add(dirLight1);

    const dirLight2 = new THREE.DirectionalLight(0x38bdf8, 1.5);
    dirLight2.position.set(-6, -4, -4);
    scene.add(dirLight2);

    const solidGroup = new THREE.Group();
    solidGroup.rotation.x = rotXRef.current;
    solidGroup.rotation.y = rotYRef.current;
    solidGroupRef.current = solidGroup;
    scene.add(solidGroup);

    buildSolidMesh(solidGroup, selectedSolid);

    // Animation Loop
    let lastTime = performance.now();
    const animate = (currentTime: number) => {
      animFrameRef.current = requestAnimationFrame(animate);
      const delta = (currentTime - lastTime) / 1000;
      lastTime = currentTime;

      if (isRotating && !isDraggingRef.current && solidGroupRef.current) {
        solidGroupRef.current.rotation.y += delta * 0.45;
        rotYRef.current = solidGroupRef.current.rotation.y;
      }

      renderer.render(scene, camera);
    };
    animFrameRef.current = requestAnimationFrame(animate);

    // Mouse / Touch Drag Event Handlers
    const handlePointerDown = (e: MouseEvent | TouchEvent) => {
      isDraggingRef.current = true;
      const clientX = 'touches' in e ? e.touches[0].clientX : e.clientX;
      const clientY = 'touches' in e ? e.touches[0].clientY : e.clientY;
      prevMousePosRef.current = { x: clientX, y: clientY };
    };

    const handlePointerMove = (e: MouseEvent | TouchEvent) => {
      if (!isDraggingRef.current || !solidGroupRef.current) return;
      const clientX = 'touches' in e ? e.touches[0].clientX : e.clientX;
      const clientY = 'touches' in e ? e.touches[0].clientY : e.clientY;

      const deltaX = clientX - prevMousePosRef.current.x;
      const deltaY = clientY - prevMousePosRef.current.y;
      prevMousePosRef.current = { x: clientX, y: clientY };

      rotYRef.current += deltaX * 0.009;
      rotXRef.current += deltaY * 0.009;

      solidGroupRef.current.rotation.y = rotYRef.current;
      solidGroupRef.current.rotation.x = rotXRef.current;

      onUpdateTransform?.({
        rotationX: rotXRef.current,
        rotationY: rotYRef.current,
        zoom: internalZoom,
      });
    };

    const handlePointerUp = () => {
      isDraggingRef.current = false;
    };

    const domElement = renderer.domElement;
    domElement.addEventListener('mousedown', handlePointerDown);
    window.addEventListener('mousemove', handlePointerMove);
    window.addEventListener('mouseup', handlePointerUp);

    domElement.addEventListener('touchstart', handlePointerDown);
    window.addEventListener('touchmove', handlePointerMove);
    window.addEventListener('touchend', handlePointerUp);

    // Responsive Resize Observer
    const resizeObserver = new ResizeObserver((entries) => {
      if (!entries[0] || !rendererRef.current || !cameraRef.current) return;
      const { width: w, height: h } = entries[0].contentRect;
      if (w > 0 && h > 0) {
        cameraRef.current.aspect = w / h;
        cameraRef.current.updateProjectionMatrix();
        rendererRef.current.setSize(w, h);
      }
    });
    resizeObserver.observe(container);

    // Cleanup on Unmount
    return () => {
      if (animFrameRef.current) cancelAnimationFrame(animFrameRef.current);
      resizeObserver.disconnect();
      domElement.removeEventListener('mousedown', handlePointerDown);
      window.removeEventListener('mousemove', handlePointerMove);
      window.removeEventListener('mouseup', handlePointerUp);
      domElement.removeEventListener('touchstart', handlePointerDown);
      window.removeEventListener('touchmove', handlePointerMove);
      window.removeEventListener('touchend', handlePointerUp);
      renderer.dispose();
      if (container.contains(domElement)) {
        container.removeChild(domElement);
      }
    };
  }, [buildSolidMesh, internalZoom, isRotating, onUpdateTransform, selectedSolid]);

  // Update camera on zoom change
  useEffect(() => {
    if (cameraRef.current) {
      cameraRef.current.position.z = 7.5 / internalZoom;
      cameraRef.current.updateProjectionMatrix();
    }
  }, [internalZoom]);

  const handleResetCamera = () => {
    rotXRef.current = 0.4;
    rotYRef.current = -0.5;
    setInternalZoom(1);
    if (solidGroupRef.current) {
      solidGroupRef.current.rotation.x = 0.4;
      solidGroupRef.current.rotation.y = -0.5;
    }
  };

  const handleZoomIn = () => setInternalZoom((z) => Math.min(2.0, z + 0.15));
  const handleZoomOut = () => setInternalZoom((z) => Math.max(0.6, z - 0.15));

  return (
    <div className="relative w-full h-full min-h-[380px] flex flex-col bg-slate-950 rounded-2xl overflow-hidden select-none">
      {/* Top Toolbar: Solid Preset Selector */}
      <div className="px-3 py-2 bg-slate-900/90 border-b border-slate-800/80 backdrop-blur-md flex items-center justify-between gap-1 overflow-x-auto z-10 scrollbar-thin">
        <div className="flex items-center space-x-1">
          <span className="p-1 rounded-md bg-amber-500/20 text-amber-400 mr-1">
            <Box className="w-3.5 h-3.5" />
          </span>
          {(['tetrahedron', 'cube', 'octahedron', 'dodecahedron', 'icosahedron', 'cylinder', 'sphere'] as const).map(
            (solid) => (
              <button
                key={solid}
                onClick={() => setSelectedSolid(solid)}
                className={`px-2 py-1 rounded-lg text-[10px] font-semibold whitespace-nowrap transition-all border ${
                  selectedSolid === solid
                    ? 'bg-amber-500 text-slate-950 font-bold border-amber-400 shadow-sm'
                    : 'bg-slate-950/80 border-slate-800 text-slate-300 hover:text-white hover:border-slate-700'
                }`}
              >
                {SOLIDS_METADATA[solid].name.split('(')[0].trim()}
              </button>
            )
          )}
        </div>

        {/* View Controls */}
        <div className="flex items-center space-x-1 shrink-0 ml-1">
          <button
            onClick={() => setIsRotating((r) => !r)}
            className={`p-1 rounded-lg text-xs transition-colors ${
              isRotating ? 'text-amber-400 bg-amber-950/40' : 'text-slate-400 hover:text-white'
            }`}
            title="Toggle Continuous Rotation"
          >
            <RotateCcw className="w-3.5 h-3.5" />
          </button>
          <button
            onClick={handleZoomOut}
            className="p-1 text-slate-400 hover:text-white rounded-lg hover:bg-slate-800"
            title="Zoom Out"
          >
            <ZoomOut className="w-3.5 h-3.5" />
          </button>
          <button
            onClick={handleZoomIn}
            className="p-1 text-slate-400 hover:text-white rounded-lg hover:bg-slate-800"
            title="Zoom In"
          >
            <ZoomIn className="w-3.5 h-3.5" />
          </button>
          <button
            onClick={handleResetCamera}
            className="p-1 text-slate-400 hover:text-white rounded-lg hover:bg-slate-800"
            title="Reset Camera"
          >
            <Maximize2 className="w-3.5 h-3.5" />
          </button>
        </div>
      </div>

      {/* Main 3D Viewport */}
      <div
        ref={mountRef}
        className="relative flex-1 w-full h-[270px] bg-slate-950 flex items-center justify-center cursor-grab active:cursor-grabbing"
      />

      {/* Euler's Characteristic & Quantitative Geometry HUD */}
      <div className="p-3 bg-slate-900/90 border-t border-slate-800/80 backdrop-blur-md space-y-2 z-10">
        <div className="grid grid-cols-4 gap-1.5 text-center">
          <div
            onClick={() => setSelectedElement('vertices')}
            className={`p-1.5 rounded-lg border cursor-pointer transition-all ${
              selectedElement === 'vertices'
                ? 'bg-amber-950/60 border-amber-500/80 text-white'
                : 'bg-slate-950/80 border-slate-800 text-slate-300 hover:border-slate-700'
            }`}
          >
            <div className="text-[10px] text-slate-400 uppercase font-mono">Vertices (V)</div>
            <div className="text-sm font-bold text-amber-300 font-mono">{currentMeta.vertices}</div>
          </div>

          <div
            onClick={() => setSelectedElement('edges')}
            className={`p-1.5 rounded-lg border cursor-pointer transition-all ${
              selectedElement === 'edges'
                ? 'bg-amber-950/60 border-amber-500/80 text-white'
                : 'bg-slate-950/80 border-slate-800 text-slate-300 hover:border-slate-700'
            }`}
          >
            <div className="text-[10px] text-slate-400 uppercase font-mono">Edges (E)</div>
            <div className="text-sm font-bold text-amber-300 font-mono">{currentMeta.edges}</div>
          </div>

          <div
            onClick={() => setSelectedElement('faces')}
            className={`p-1.5 rounded-lg border cursor-pointer transition-all ${
              selectedElement === 'faces'
                ? 'bg-amber-950/60 border-amber-500/80 text-white'
                : 'bg-slate-950/80 border-slate-800 text-slate-300 hover:border-slate-700'
            }`}
          >
            <div className="text-[10px] text-slate-400 uppercase font-mono">Faces (F)</div>
            <div className="text-sm font-bold text-amber-300 font-mono">{currentMeta.faces}</div>
          </div>

          <div
            onClick={() => setSelectedElement('euler')}
            className={`p-1.5 rounded-lg border cursor-pointer transition-all ${
              selectedElement === 'euler'
                ? 'bg-cyan-950/60 border-cyan-500/80 text-white'
                : 'bg-slate-950/80 border-slate-800 text-slate-300 hover:border-slate-700'
            }`}
          >
            <div className="text-[10px] text-cyan-400 uppercase font-mono">V - E + F</div>
            <div className="text-sm font-bold text-cyan-300 font-mono">
              {currentMeta.vertices - currentMeta.edges + currentMeta.faces === 2 ? '2 ✓' : currentMeta.eulerCharacteristic}
            </div>
          </div>
        </div>

        {/* Selected Element Educational Detail */}
        <div className="p-2 rounded-xl bg-slate-950/90 border border-slate-800 text-[11px] space-y-1">
          <div className="flex items-center justify-between">
            <span className="font-bold text-amber-300">{currentMeta.name}</span>
            <span className="text-[10px] text-slate-400 font-mono">{currentMeta.symmetry}</span>
          </div>
          <p className="text-slate-300 leading-snug">{currentMeta.description}</p>
          <div className="grid grid-cols-2 gap-2 pt-1 border-t border-slate-800/80 text-[10px] font-mono text-slate-300">
            <div>
              <span className="text-slate-400">Surface Area:</span> {currentMeta.formulaSurface}
            </div>
            <div>
              <span className="text-slate-400">Volume:</span> {currentMeta.formulaVolume}
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};

